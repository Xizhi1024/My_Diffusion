def find_source_docx() -> Path:
    candidates = sorted(
        Path("output/patent_disclosure").glob("*.docx"),
        key=lambda p: p.stat().st_mtime,
        reverse=True,
    )
    for candidate in candidates:
        try:
            doc = Document(candidate)
        except Exception:
            continue
        first_text = doc.paragraphs[0].text.strip() if doc.paragraphs else ""
        if first_text.startswith("初步名称"):
            return candidate
    raise FileNotFoundError("Could not find the current patent disclosure docx.")


