def replace_paragraph_text(paragraph, text: str) -> None:
    """Replace paragraph text while preserving the first run's character style."""
    if paragraph.runs:
        first = paragraph.runs[0]
        for run in paragraph.runs:
            run.text = ""
        first.text = text
        # Ensure East Asian font stays readable after replacement.
        if first._r.rPr is None:
            first._r.get_or_add_rPr()
        first._r.rPr.rFonts.set(qn("w:eastAsia"), "SimSun")
    else:
        paragraph.add_run(text)


